package domain;

public class Industry {
    private final String mapName;
    IndustryType type;
    private Location location;
    private final int generatedIron;
    private final int generatedCoal;
    private int storedIron;
    private int storedCoal;
    private int storedSteel;
    private final int area;

    /**
     * Constructs an Industry instance with the specified map name, industry type,
     * and location coordinates.
     *
     * @param mapName   the name of the map where the industry is located
     * @param type      the type of the industry (e.g., IRON_MINE, COAL_MINE)
     * @param positionX the x-coordinate of the industry's location
     * @param positionY the y-coordinate of the industry's location
     */
    public Industry(String mapName, IndustryType type, int positionX, int positionY) {
        this.mapName = mapName;
        this.type = type;
        this.location = new Location(positionX, positionY);
        this.generatedIron = 14;
        this.generatedCoal = 16;
        this.storedIron = 0;
        this.storedCoal = 0;
        this.storedSteel = 0;
        this.area = 9;
    }

    /**
     * Returns the name of the map associated with this Industry.
     *
     * @return the name of the map
     */
    public String getMapName() {
        return mapName;
    }

    /**
     * Returns the type of the current industry.
     *
     * @return the IndustryType of this industry
     */
    public IndustryType getType() {
        return type;
    }

    /**
     * Sets the type of the current industry.
     *
     * @param type the new type of the industry (e.g., IRON_MINE, COAL_MINE)
     */
    public void setType(IndustryType type) {
        this.type = type;
    }

    /**
     * Returns the location of this Industry.
     *
     * @return the Location object representing the coordinates of this Industry
     */
    public Location getLocation() {
        return location;
    }

    /**
     * Sets the location of this Industry.
     */
    public void setLocation(Location location) {
        this.location = location;
    }

    /**
     * Returns the amount of iron generated by this industry.
     *
     * @return the amount of generated iron
     */
    public int getGeneratedIron() {
        return generatedIron;
    }

    /**
     * Returns the amount of coal generated by this industry.
     *
     * @return the amount of generated coal
     */
    public int getGeneratedCoal() {
        return generatedCoal;
    }

    /**
     * Returns the current amount of stored iron in the industry.
     *
     * @return the amount of stored iron
     */
    public int getStoredIron() {
        return storedIron;
    }

    /**
     * Sets the current amount of stored iron in the industry.
     *
     * @param storedIron the new amount of stored iron
     */
    public void setStoredIron(int storedIron) {
        this.storedIron = storedIron;
    }

    /**
     * Retrieves the current amount of coal stored in the industry.
     *
     * @return the amount of stored coal
     */
    public int getStoredCoal() {
        return storedCoal;
    }

    /**
     * Sets the current amount of stored coal in the industry.
     *
     * @param storedCoal the new amount of stored coal to be set
     */
    public void setStoredCoal(int storedCoal) {
        this.storedCoal = storedCoal;
    }

    /**
     * Retrieves the current amount of steel stored in the industry.
     *
     * @return the amount of stored steel
     */
    public int getStoredSteel() {
        return storedSteel;
    }

    /**
     * Sets the current amount of stored steel in the industry.
     *
     * @param storedSteel the new amount of stored steel
     */
    public void setStoredSteel(int storedSteel) {
        this.storedSteel = storedSteel;
    }

    /**
     * Retrieves the area of the industry.
     *
     * @return the area of the industry as an integer
     */
    public int getArea() {
        return area;
    }

    /**
     * Returns a string representation of the Industry object.
     * The representation includes the type and location of the industry.
     *
     * @return a string describing the Industry instance
     */
    @Override
    public String toString() {
        return "Industry{" +
                "type=" + type +
                ", location=" + location +
                '}';
    }

}
